/* сборка полного пула темы: вариант ФИПИ + банк преподавателя + демо-набор */
function buildPool(number: number, extra?: CustomTask[]): FeedTask[] {
  const fromVariant: FeedTask[] = REAL_VARIANT.filter((t) => t.number === number && t.answer)
    .map((t) => ({
      id: `v-${t.number}`, number: t.number, topic: t.category,
      statement: t.statement, answer: t.answer as string, solution: t.solution ?? t.criteria, imageUrls: t.imageUrls,
    }));
  const fromBank: FeedTask[] = (extra ?? [])
    .filter((t) => t.exam_type === "ege" && t.task_number === number && !t.is_second_part && t.correct_answer)
    .map((t) => ({
      id: t.id, number: t.task_number, topic: t.topic,
      statement: t.condition_text, answer: t.correct_answer as string, solution: t.solution_text,
    }));
  const demo: Row[] = number === 4 ? SIMPLE_PROB : number === 5 ? COMPLEX_PROB : [];
  const fromDemo: FeedTask[] = demo.map(([text, answer, explain], i) => ({
    id: `d${number}-${i + 1}`, number,
    topic: number === 4 ? "Простая вероятность" : "Сложная вероятность",
    statement: text, answer, solution: explain,
  }));
  /* дедупликация по условию (вдруг задача есть и в варианте, и в банке) */
  const seen = new Set<string>();
  return [...fromVariant, ...fromBank, ...fromDemo].filter((t) => {
    const key = t.statement.replace(/\s+/g, " ").trim().slice(0, 120);
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  });
}

/* ─────────────── «сеть»: демо имитирует бэкенд с задержкой ─────────────── */
const wait = (ms: number) => new Promise((r) => setTimeout(r, ms));

/**
 * Страница пула темы: только задачи, которые пользователь ещё НЕ решил верно.
 * limit/offset считаются внутри отфильтрованного (нерешённого) списка —
 * зеркалит бэкенд, где дубли исключаются JOIN'ом по user_id + task_id.
 */
export async function fetchTopicFeed(
  number: number,
  { limit, offset = 0, solvedIds, extra }: FeedOptions
): Promise<FeedPage> {
  await wait(260);
  const pool = buildPool(number, extra);
  const unsolved = pool.filter((t) => !solvedIds.includes(t.id));
  const items = unsolved.slice(offset, limit === undefined ? undefined : offset + limit);
  const solved = pool.length - unsolved.length;
  return {
    items,
    meta: {
      total: pool.length,
      solved,
      remaining: unsolved.length,
      hasMore: offset + items.length < unsolved.length,
    },
  };
}

/* ─────────────── проверка ответа: числовое сравнение ───────────────
   «0,15», «0.15» и «0.150» — один и тот же ответ: запятая → точка,
   дальше сравнение как чисел (0.150 === 0.15), а не строк. */
export function normalizeAnswer(raw: string): string {
  return raw.trim().toLowerCase().replace(/\s+/g, "").replace(/,/g, ".");
}

export function answersMatchNumeric(given: string, reference: string): boolean {
  const g = normalizeAnswer(given);
  const r = normalizeAnswer(reference);
  if (!g) return false;
  if (g === r) return true;
  const ng = Number(g);
  const nr = Number(r);
  return Number.isFinite(ng) && Number.isFinite(nr) && Math.abs(ng - nr) < 1e-9;
}

export interface CheckVerdict {
  correct: boolean;
  normalizedGiven: string;
  normalizedAnswer: string;
}

export async function checkTaskAnswer(task: FeedTask, given: string): Promise<CheckVerdict> {
  await wait(180);
  return {
    correct: answersMatchNumeric(given, task.answer),
    normalizedGiven: normalizeAnswer(given),
    normalizedAnswer: normalizeAnswer(task.answer),
  };
}
