/* ══════════════════════════════════════════════════════════════════
   Лента задач темы (Task Feed).
   Единый контракт для демо-режима и реального бэкенда:
     fetchTopicFeed(№, { limit, offset, solvedIds, extra }) → страница пула
     checkTaskAnswer(task, answer) → вердикт (числовое сравнение)

   Бэкенд (см. backend/app/main.py):
     GET  /api/topics/{number}/feed?limit&offset   — только нерешённые
                                                     (JOIN progress по user_id)
     POST /api/tasks/{id}/check                    — нормализация , → .
   ══════════════════════════════════════════════════════════════════ */
import { REAL_VARIANT } from "./data";
import type { CustomTask } from "./store";

export interface FeedTask {
  id: string;
  number: number;
  topic: string;
  statement: string;
  answer: string;
  solution?: string;
  imageUrls?: string[];
}

export interface FeedMeta {
  total: number;    // всего задач в теме
  solved: number;   // решено верно пользователем
  remaining: number;
  hasMore: boolean; // есть ли ещё нерешённые после этой страницы
}

export interface FeedPage {
  items: FeedTask[];
  meta: FeedMeta;
}

export interface FeedOptions {
  limit?: number;   // undefined → вся оставшаяся очередь
  offset?: number;  // сдвиг внутри НЕрешённых задач
  solvedIds: string[];
  extra?: CustomTask[]; // задачи, добавленные преподавателем в кабинете
}

